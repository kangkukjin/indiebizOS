"""Admit exact owner-generated vocabulary outputs without opening core writes.

The trusted deployed builder declares output paths/markers. The candidate must
pass the existing builder check; document prose remains exactly at its baseline.
This is validation of generated bytes, not an agent-provided scope exception.
"""
import json
from pathlib import Path
import re
import subprocess
import sys


def contract():
    from runtime_utils import get_code_root
    root = Path(get_code_root())
    process = subprocess.run([sys.executable, str(root / 'scripts/build_ibl_nodes.py'), '--outputs-json'],
                             cwd=root, capture_output=True, text=True, timeout=30, check=True)
    return json.loads(process.stdout)


def accept(candidate, repo, session, current, changes):
    from program_boundary import candidate_plan, may_have_derived_content
    scope = candidate_plan(session, current)
    candidates = [*scope['protected'], *scope['unmanaged']]
    candidates = [p for p in candidates if p not in session.get('derived_files', {})
                  and p not in session.get('artifact_paths', [])]
    if not candidates:
        return
    if any(not may_have_derived_content(p) for p in candidates):
        raise PermissionError('일반 프로그램 수리 범위 밖 변경: ' + ', '.join(candidates))
    schema = contract()
    documents = {}
    for rel, start, end in schema['documents']:
        documents.setdefault(rel, []).append((start, end))
    recognized = set(schema['files']) | documents.keys()
    # An unrecognized/protected implementation must fail before a candidate
    # script is ever executed, including attempts to change builder helpers.
    outside = set(candidates) - recognized
    if outside:
        raise PermissionError('일반 프로그램 수리 범위 밖 변경: ' + ', '.join(sorted(outside)))
    wt = Path(repo) / session['worktree']
    for rel in candidates:
        if rel not in documents:
            continue
        live = candidate.target(repo, rel)
        if candidate.fingerprint(live) != session['baseline'].get(rel):
            raise ValueError('파생 문서의 정본 충돌: ' + rel)
        before, after = live.read_text(), candidate.target(wt, rel).read_text()
        for start, end in documents[rel]:
            pattern = re.escape(start) + '.*?' + re.escape(end)
            if before.count(start) != 1 or after.count(start) != 1 or after.count(end) != 1:
                raise PermissionError('파생 문서 마커 변경: ' + rel)
            before = re.sub(pattern, '', before, flags=re.S)
            after = re.sub(pattern, '', after, flags=re.S)
        if before != after:
            raise PermissionError('파생 마커 밖 문서 변경: ' + rel)
    from repair_process import run
    import os
    environment = {**os.environ, 'INDIEBIZ_BASE_PATH': str(wt), 'PYTHONDONTWRITEBYTECODE': '1'}
    result = run([sys.executable, 'scripts/build_ibl_nodes.py', '--check'], str(wt), cwd=wt,
                 env=environment, capture_output=True, text=True, timeout=300)
    if result.returncode:
        raise ValueError('어휘 파생물 소유 검사 실패: ' + (result.stderr + result.stdout)[-1200:])
    if any(candidate.fingerprint(candidate.target(wt, rel)) != current.get(rel) for rel in changes):
        raise ValueError('어휘 검사 중 후보 변경')
    session.setdefault('derived_files', {}).update({p: current[p] for p in candidates})
