// Read-only post-activation check against the controller's allowed live URL.
import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
const base = process.env.INDIEBIZ_VERIFY_BASE_URL;
assert.ok(base, 'Controller must provide INDIEBIZ_VERIFY_BASE_URL');
const response = await fetch(new URL('/xray/app', base), {signal: AbortSignal.timeout(15000)});
assert.equal(response.status, 200);
const html = await response.text();
const bundle = JSON.parse(fs.readFileSync(new URL('../i18n/xray.json', import.meta.url)));
assert.equal(html, bundle.html, 'Live X-Ray must serve the verified Japanese bundle');
const bootstrap = [...html.matchAll(/<script\b[^>]*>([\s\S]*?)<\/script>/gi)].map(m=>m[1]).find(s=>s.includes('window.__ui='));
assert.ok(bootstrap, 'Live UI bootstrap missing');
const stored = new Map([['indiebiz.ui.locale','ja']]);
const window = {localStorage:{getItem:k=>stored.get(k),setItem:(k,v)=>stored.set(k,v)},addEventListener(){}};
const document = {documentElement:{},addEventListener(){},referrer:''};
window.document = document;
vm.runInNewContext(bootstrap, {window, document, parent:window, URL, location:{href:new URL('/xray/app',base).href}, history:{replaceState(){}}});
assert.equal(window.__ui.languages.ja,'日本語');
assert.equal(window.__ui.getLocale(),'ja');
assert.equal(document.documentElement.lang,'ja');
const catalog = JSON.parse(fs.readFileSync(new URL('../i18n/catalog.json',import.meta.url)));
const [id,m] = Object.entries(catalog.messages).find(([,m])=>m.context.startsWith('xray:') && m.source==='새로고침');
assert.equal(window.__ui.text(id),m.translations.ja);
window.__ui.setLocale('ko');
assert.equal(window.__ui.text(id),m.source);
window.__ui.setLocale('ja');
assert.equal(window.__ui.text(id),m.translations.ja);
console.log(JSON.stringify({liveXrayBundleMatches:true,loadedLocale:'ja',refresh:window.__ui.text(id),switchRestore:true}));
